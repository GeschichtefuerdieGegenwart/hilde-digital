def url(s):
    datei, _, anker = s.partition("#")
    return (W / datei).as_uri() + ("#" + anker if anker else "")


def pruefe(bed, text):
    print(("✓ " if bed else "✗ ") + text)
    if not bed:
        fehler.append(text)


def neue_seite(browser, **kw):
    ctx = browser.new_context(viewport=kw.pop("viewport", {"width": 1280, "height": 720}), **kw)
    # Ohne Internet: jede Anfrage außerhalb von file:// wird blockiert und gezählt.
    extern = []
    ctx.route("**/*", lambda r: (extern.append(r.request.url), r.abort()) if not r.request.url.startswith("file:") else r.continue_())
    pg = ctx.new_page()
    pg.konsole = []
    pg.extern = extern
    # Chromium meldet beim schnellen Seitenwechsel unter file:// eine abgebrochene Seitenüberblendung
    # (@view-transition in hilde.css) als Konsolenfehler. Das ist kein Fehler der Seite und wird übergangen.
    pg.on("console", lambda m: m.type == "error" and "ViewTransition" not in m.text and pg.konsole.append(m.text))
    pg.on("pageerror", lambda e: "ViewTransition" not in str(e) and pg.konsole.append(str(e)))
    return pg


